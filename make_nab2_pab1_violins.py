"""
Nab2p vs Pab1p per-transcript co-purification enrichment across the eight
AP-RNA-seq transcript clusters C1–C8 (split violins side by side).

Reproduces `Nab2_Pab1_violins_byCluster.pdf` (built inline 2026-10-07) as a
saved, reproducible script. Successor to Spotlight Figure Y in
make_spotlight_figures.py (which plots one bait per panel).

Method
  Data     data/rna_gene_clusters.tsv — all 2,434 co-enriched transcripts
           (enrichment > 0.3 in at least one of the 18 baits), per-bait mean
           max-normalized enrichment + cluster label C1–C8
           (clusters regenerated by make_rna_gene_clusters.py).
  Plot     for each cluster, the distribution of per-transcript enrichment for
           NAB2 and PAB1 (matplotlib violinplot, KDE cut at data range);
           black bar = median. Background = cluster color (CLUSTER_COLORS).
  MTR2 is not involved (comparison of two RNA baits).

Panel    Supplemental Figure 5E (added 2026-10-28)
Stats    paired Wilcoxon signed-rank test Nab2p vs Pab1p per cluster, Benjamini–Hochberg
         correction over the eight clusters; Spearman ρ Nab2p vs Pab1p across all transcripts
Output   output/nab2_pab1_violins_byCluster.pdf (+ .png), panel letter via --letter
Usage    python3 make_nab2_pab1_violins.py [--letter E]
"""
import os
import sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from figure_style import (apply_style, GROUP_COLORS, CLUSTER_COLORS,
                          CLUSTER_ORDER, CLUSTER_LABELS, fmt_bait)
apply_style()
plt.rcParams['pdf.fonttype'] = 42

DATADIR = os.path.join(HERE, "data")
OUTDIR = os.path.join(HERE, "output")
os.makedirs(OUTDIR, exist_ok=True)
LETTER = sys.argv[sys.argv.index("--letter") + 1] if "--letter" in sys.argv else "E"

BAITS = ['NAB2', 'PAB1']
BAIT_COLS = {'NAB2': GROUP_COLORS['Co-Txp/THO/TREX'],   # #338FBF blue
             'PAB1': GROUP_COLORS['Cytoplasmic']}       # #DC9C3C amber
OFFSET, WIDTH = 0.2, 0.36

df = pd.read_csv(os.path.join(DATADIR, "rna_gene_clusters.tsv"), sep='\t', index_col=0)

fig, ax = plt.subplots(figsize=(9.2, 4.0))
fig.patch.set_facecolor('white')
medians = {}
for i, k in enumerate(CLUSTER_ORDER):
    ax.axvspan(i - 0.5, i + 0.5, color=CLUSTER_COLORS[k], alpha=0.10, zorder=0, lw=0)
    if i:
        ax.axvline(i - 0.5, color='#DDDDDD', linewidth=0.6, zorder=1)
    sub = df[df['cluster'] == k]
    for j, b in enumerate(BAITS):
        pos = i + (-OFFSET if j == 0 else OFFSET)
        vals = sub[b].values
        vp = ax.violinplot([vals], positions=[pos], widths=WIDTH,
                           showmedians=False, showextrema=False)
        for body in vp['bodies']:
            body.set_facecolor(BAIT_COLS[b]); body.set_edgecolor('none'); body.set_alpha(0.85)
            body.set_zorder(2)
        med = float(np.median(vals))
        medians[(b, k)] = (med, len(vals))
        ax.hlines(med, pos - 0.06, pos + 0.06, color='black', linewidth=1.4, zorder=3)

ax.set_xticks(range(len(CLUSTER_ORDER)))
ax.set_xticklabels([CLUSTER_LABELS[k].replace('\n', ' ') for k in CLUSTER_ORDER],
                   rotation=30, ha='right', fontsize=7)
ax.set_xlim(-0.5, len(CLUSTER_ORDER) - 0.5)
ax.set_ylim(0, 1.02)
ax.set_ylabel('Transcript enrichment', fontsize=9)
ax.tick_params(axis='y', labelsize=8)
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
ax.legend(handles=[mpatches.Patch(color=BAIT_COLS[b], alpha=0.85, label=fmt_bait(b)) for b in BAITS],
          loc='upper right', fontsize=7.5, frameon=False)
ax.set_title('Nab2p and Pab1p transcript enrichment by RNA cluster\n'
             '(per-transcript enrichment; black bars, medians)',
             fontsize=7.5, fontweight='bold')
ax.text(-0.09, 1.06, LETTER, transform=ax.transAxes, fontsize=14, fontweight='bold')

fig.savefig(os.path.join(OUTDIR, "nab2_pab1_violins_byCluster.pdf"), bbox_inches='tight', facecolor='white')
fig.savefig(os.path.join(OUTDIR, "nab2_pab1_violins_byCluster.png"), dpi=150, bbox_inches='tight', facecolor='white')

print(f"{len(df)} transcripts")
print("cluster   n     Nab2p median  Pab1p median")
for k in CLUSTER_ORDER:
    print(f"  C{k}   {medians[('NAB2', k)][1]:4d}     {medians[('NAB2', k)][0]:.2f}          {medians[('PAB1', k)][0]:.2f}")

# ── Statistics (reported in the Results / legend) ───────────────────────────
from scipy.stats import wilcoxon, spearmanr
rho, p_rho = spearmanr(df['NAB2'], df['PAB1'])
print(f"Nab2p vs Pab1p across all {len(df)} transcripts: Spearman rho = {rho:.2f} (p = {p_rho:.1e})")
pvals = []
for k in CLUSTER_ORDER:
    sub = df[df['cluster'] == k]
    pvals.append(wilcoxon(sub['NAB2'], sub['PAB1']).pvalue)
pvals = np.array(pvals); order = np.argsort(pvals); m = len(pvals)
qvals = np.empty(m); running = 1.0
for rank in range(m - 1, -1, -1):          # Benjamini–Hochberg step-up
    running = min(running, pvals[order[rank]] * m / (rank + 1)); qvals[order[rank]] = running
print("cluster  paired Wilcoxon p   BH q      fraction Pab1p > Nab2p")
for i, k in enumerate(CLUSTER_ORDER):
    sub = df[df['cluster'] == k]
    print(f"  C{k}     {pvals[i]:.1e}        {qvals[i]:.1e}   {(sub['PAB1'] > sub['NAB2']).mean():.2f}")
